def source_files(links: list[dict[str, str]]) -> str:
    aha = next((item["url"] for item in links
                if "ahaslides" in (item.get("name", "") + item.get("url", "")).lower()), None)
    slides = f"[HTML]({POST_URL}slides/index.html) and " + (
        f"[interactive slides (AhaSlides)]({aha})" if aha
        else f"interactive slides (AhaSlides), linked from the [published post]({POST_URL})")
    return "\n".join([
        "## Source files",
        "",
        f"- Companion script: [`script.py`]({RAW}script.py), also in this bundle",
        f"- Cheat sheets, also in this bundle: [`cheatsheet_python.py`]({RAW}cheatsheet_python.py), "
        f"[`cheatsheet_R.R`]({RAW}cheatsheet_R.R), and [`cheatsheet_stata.do`]({RAW}cheatsheet_stata.do)",
        f"- Data in this bundle: `smoking_sc.csv`, with the same values as the "
        f"[Stata file]({DATA_URL}) that the post loads",
        f"- Data dictionary: <{POST_URL}data/index.html>",
        f"- Slides: {slides}",
        f"- Interactive web app: <{POST_URL}web_app/index.html>",
        f"- Google Colab notebook: <{COLAB_URL}>",
        f"- Stata edition of this post: <{SITE}/post/stata_sc/>",
        f"- Published post: <{POST_URL}>",
        f"- GitHub repository: <{REPO_URL}>",
    ])


def build_qmd(front: str, root: Node) -> str:
    used: dict[str, int] = {}
    title = front_scalar(front, "title")
    date = front_scalar(front, "date")[:10]
    parts = [qmd_header(title, date),
             *callout("callout-important", "How to render this tutorial", RENDER_BLOCKS),
             setup_packages_chunk(),
             *qmd_nodes(root.children, used),
             source_files(front_links(front))]
    check_wording(COMMON_WORDING, used)
    return "\n\n".join(parts) + "\n"


