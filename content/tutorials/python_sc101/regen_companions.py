def is_paragraph(block: str) -> bool:
    return not re.match(r"^(```|#|\||[-*+] |\d+\. |\$\$|<|:::|>)", block)


def callout(cls: str, title: str, inner: list[str], *, collapse: bool = False,
            simple: bool = False) -> list[str]:
    """Wrap blocks in a Quarto callout whose fences touch the first and the last paragraph."""
    if not inner or not is_paragraph(inner[0]):
        raise SystemExit(f"the callout {title!r} must open with a paragraph")
    last_line = inner[-1].split("\n")[-1]
    if not (is_paragraph(last_line) or last_line == ":::"):
        raise SystemExit(f"the callout {title!r} must close after a paragraph")
    if '"' in title:
        if "'" in title:
            raise SystemExit(f"the callout title {title!r} mixes both kinds of quotes")
        quoted = f"'{title}'"
    else:
        quoted = f'"{title}"'
    attrs = f".{cls}" + (' collapse="true"' if collapse else "") + \
        (' appearance="simple"' if simple else "") + f" title={quoted}"
    inner = list(inner)
    inner[0] = "::: {" + attrs + "}\n" + inner[0]
    inner[-1] = inner[-1] + "\n:::"
    return inner


def qmd_fence(node: Node) -> list[str]:
    if node.lang == "text":
        return []                      # the render prints fresh output
    if node.lang == "mermaid":
        return ["```{mermaid}\n" + node.code + "```"]
    if node.lang != "python":
        return [f"```{node.lang}\n{node.code}```"]
    opts = [f"#| label: {node.label}"]
    if node.fig is not None:
        caption = re.sub(r"^Figure \d+\.\s+", "", node.fig.caption)
        opts += [f"#| fig-cap: {yaml_str(caption)}", f"#| fig-alt: {yaml_str(node.fig.alt)}"]
    if getattr(node, "solution", None):
        opts.append("#| code-fold: false")
    return ["```{python}\n" + "\n".join(opts) + "\n\n" + node.code + "```"]


def qmd_nodes(nodes: list[Node], used: dict[str, int]) -> list[str]:
    out: list[str] = []
    for node in nodes:
        if node.kind == "md":
            out += md_blocks(undo_escapes(common_text(node.text, used), currency="$"))
        elif node.kind == "fence":
            out += qmd_fence(node)
        elif node.kind in ("image", "badge"):
            continue                   # the plotting chunk carries the caption; no badge
        elif node.kind == "shortcode":
            note = LAB_NOTE.format(url=f"{POST_URL}#{node.anchor}")
            out += callout("callout-note", "Web version only", [note])
        elif node.kind == "div":
            out += qmd_div(node, used)
        elif node.kind == "details":
            out += qmd_details(node, used)
        else:
            raise SystemExit(f"no Quarto rule for a {node.kind} node")
    return out


def qmd_div(node: Node, used: dict[str, int]) -> list[str]:
    if node.cls == "concept-pair":
        return qmd_nodes(node.children, used)
    if node.cls == "learn-card predict-card":
        kicker, *rest = node.children
        if kicker.kind != "kicker":
            raise SystemExit("a predict card must start with its kicker")
        return callout("callout-tip", kicker.text, qmd_nodes(rest, used))
    raise SystemExit(f"no Quarto rule for <div class={node.cls!r}>")


def qmd_details(node: Node, used: dict[str, int]) -> list[str]:
    blocks = qmd_nodes(node.children, used)
    cls = node.cls
    if cls == "":
        return blocks                  # plotting code: code-fold already hides it
    if cls in ("concept-card concept-example", "concept-card concept-analogy"):
        return callout("callout-note", node.summary, blocks, collapse=True, simple=True)
    if cls == "learn-card-reveal":
        return callout("callout-note", node.summary, blocks, collapse=True)
    if cls == "learn-card misconception-card":
        return callout("callout-warning", f"{node.kicker}: {node.summary}", blocks, collapse=True)
    if cls == "learn-card proof-card":
        return callout("callout-note", f"{node.kicker}: {node.summary}", blocks, collapse=True)
    if cls == "learn-card solution-card":
        return callout("callout-note", f"Solution to Exercise {node.exercise}",
                       [QMD_SOLUTION_LEAD, *blocks], collapse=True)
    raise SystemExit(f"no Quarto rule for <details class={cls!r}>")


