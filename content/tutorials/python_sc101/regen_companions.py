class NotebookCells:
    """Collect Markdown blocks into cells, with a new cell at every heading."""

    def __init__(self):
        self.cells: list[tuple[str, str]] = []
        self.buf: list[str] = []

    def md(self, block: str) -> None:
        if block.startswith("#") and self.buf:
            self.flush()
        self.buf.append(block)

    def flush(self) -> None:
        if self.buf:
            self.cells.append(("markdown", "\n\n".join(self.buf)))
            self.buf = []

    def code(self, source: str) -> None:
        self.flush()
        self.cells.append(("code", source.rstrip("\n")))


class NotebookBuilder:
    def __init__(self):
        self.nb = NotebookCells()
        self.used: dict[str, int] = {}
        self.drop_colors = False

    def text(self, raw: str) -> list[str]:
        t = common_text(raw, self.used)
        t = apply_wording(t, NOTEBOOK_WORDING, self.used)
        return md_blocks(undo_escapes(t, currency="\\$"))

    def card_blocks(self, node: Node) -> list[str]:
        if any(c.kind != "md" for c in node.children):
            raise SystemExit(f"the card {node.summary!r} may contain only text in the notebook")
        return [b for c in node.children for b in self.text(c.text)]

    def nodes(self, nodes: list[Node]) -> None:
        nb = self.nb
        for node in nodes:
            if node.kind == "md":
                for block in self.text(node.text):
                    if self.drop_colors:
                        if not block.startswith(COLORS_PARAGRAPH):
                            raise SystemExit("the paragraph after the diagram changed; "
                                             "update COLORS_PARAGRAPH")
                        self.drop_colors = False
                        continue
                    nb.md(block)
            elif node.kind == "fence":
                if node.lang == "python":
                    nb.code(node.code)
                elif node.lang == "mermaid":
                    missing = [f for f in STUDY_DESIGN_FACTS if f not in node.code]
                    if missing:
                        raise SystemExit("the Mermaid diagram of index.md changed; update "
                                         "STUDY_DESIGN in regen_companions.py: " + "; ".join(missing))
                    nb.md(STUDY_DESIGN)
                    self.drop_colors = True
                elif node.lang != "text":
                    nb.md(f"```{node.lang}\n{node.code}```")
            elif node.kind == "image":
                if re.search(r"[*_`\[]", node.caption):
                    raise SystemExit(f"the caption of {node.src} needs a Markdown-safe rewrite")
                nb.md(f"<em>{node.caption}</em>")
            elif node.kind == "badge":
                continue                   # the badge sits in the first cell
            elif node.kind == "shortcode":
                note = LAB_NOTE.format(url=f"{POST_URL}#{node.anchor}")
                nb.md(f"> **Web version only.** {note}")
            elif node.kind == "div":
                self.div(node)
            elif node.kind == "details":
                self.details(node)
            else:
                raise SystemExit(f"no notebook rule for a {node.kind} node")

    def div(self, node: Node) -> None:
        if node.cls == "concept-pair":
            self.nodes(node.children)
            return
        if node.cls != "learn-card predict-card":
            raise SystemExit(f"no notebook rule for <div class={node.cls!r}>")
        kicker, *rest = node.children
        reveal = [c for c in rest if c.kind == "details"]
        if kicker.kind != "kicker" or len(reveal) != 1 or rest[-1] is not reveal[0]:
            raise SystemExit("a predict card needs a kicker, text, and one reveal at the end")
        blocks = [b for c in rest[:-1] for b in self.text(c.text)]
        blocks[0] = f"**{kicker.text}.** " + blocks[0]
        quote = "\n>\n".join("\n".join("> " + line for line in b.split("\n")) for b in blocks)
        self.nb.md(quote)
        answer = "\n\n".join(self.card_blocks(reveal[0]))
        self.nb.md(f"<details>\n<summary>{reveal[0].summary}</summary>\n\n{answer}\n\n</details>")

    def details(self, node: Node) -> None:
        cls = node.cls
        if cls == "":
            self.nodes(node.children)      # plotting code becomes an ordinary code cell
            return
        if cls == "learn-card solution-card":
            self.nb.md(NB_SOLUTION_LEAD)
            self.nodes(node.children)
            return
        blocks = self.card_blocks(node)
        if cls in ("concept-card concept-example", "concept-card concept-analogy"):
            blocks[0] = f"**{node.summary}.** " + blocks[0]
        elif cls == "learn-card misconception-card":
            blocks[0] = f"**{node.kicker}:** {node.summary}<br>\n" + blocks[0]
        elif cls == "learn-card proof-card":
            blocks[0] = f"**{node.kicker} (optional).** *{node.summary}.*<br>\n" + blocks[0]
        else:
            raise SystemExit(f"no notebook rule for <details class={cls!r}>")
        for block in blocks:
            self.nb.md(block)


def build_ipynb(front: str, root: Node) -> str:
    title = front_scalar(front, "title")
    builder = NotebookBuilder()
    nb = builder.nb
    badge = (f'<a href="{COLAB_URL}" target="_blank" rel="noopener">'
             f'<img src="{BADGE_URL}" alt="Open In Colab"></a>')
    nb.md(f"# {title}")
    nb.md(NB_INTRO.format(title=title, url=POST_URL))
    nb.md(badge)
    nb.md(NB_RUNTIME)
    nb.md("## Install the packages")
    nb.md(NB_INSTALL)
    nb.code(NB_PIP)
    nb.code(NB_VERSION_CHECK)
    builder.nodes(root.children)
    footer = source_files(front_links(front))
    # The notebook travels without the bundle, so the footer drops the bundle wording.
    footer = (footer.replace(", also in this bundle", "")
              .replace("Cheat sheets, also in this bundle:", "Cheat sheets:")
              .replace("- Data in this bundle: `smoking_sc.csv`",
                       f"- Data: [`smoking_sc.csv`]({RAW}data/smoking_sc.csv)"))
    nb.md(footer)
    nb.flush()
    check_wording(NOTEBOOK_WORDING, builder.used)
    cells = []
    for k, (kind, source) in enumerate(nb.cells):
        lines = source.split("\n")
        cell = {"cell_type": kind, "id": f"cell-{k:03d}", "metadata": {},
                "source": [line + "\n" for line in lines[:-1]] + [lines[-1]]}
        if kind == "code":
            cell.update(execution_count=None, outputs=[])
        cells.append(cell)
    notebook = {
        "cells": cells,
        "metadata": {
            "colab": {"provenance": [], "toc_visible": True},
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    return json.dumps(notebook, indent=1, ensure_ascii=False, sort_keys=True) + "\n"


