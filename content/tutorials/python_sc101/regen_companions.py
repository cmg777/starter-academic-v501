def check_pins() -> None:
    """Make the verification chunk agree with the pins of setup_env.py."""
    env = POST / "references" / "setup_env.py"
    if not env.exists():
        return
    pins = dict(re.findall(r'^\s+"([\w-]+)":\s+"([^"]+)",', env.read_text(encoding="utf-8"), re.M))
    for package, version in HEADLINE.items():
        if pins.get(package) != version:
            raise SystemExit(f"setup_env.py pins {package} {pins.get(package)}, "
                             f"but HEADLINE expects {version}")


def main(argv: list[str]) -> int:
    if any(a != "--check" for a in argv):
        print(__doc__)
        return 2
    check = "--check" in argv
    check_pins()
    front, body, offset = split_front_matter((POST / "index.md").read_text(encoding="utf-8"))
    root = parse_body(body, offset)
    stats = annotate(root)
    outputs = {QMD_PATH: build_qmd(front, root), IPYNB_PATH: build_ipynb(front, root)}
    if check:
        stale = [p for p, text in outputs.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(POST)} (run python3 regen_companions.py)")
        if not stale:
            print("tutorial.qmd and notebook.ipynb match index.md")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    cards = ", ".join(f"{v} {k}" for k, v in sorted(stats["cards"].items()))
    print(f"wrote references/tutorial.qmd and notebook.ipynb: {stats['python']} python chunks, "
          f"{stats['figures']} figures, lab anchor #{stats['lab_anchor']}")
    print(f"cards: {cards}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
