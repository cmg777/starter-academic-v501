def md_blocks(text: str) -> list[str]:
    """Split Markdown into blocks at blank lines, without empty blocks."""
    return [b.strip("\n") for b in re.split(r"\n[ \t]*\n", text) if b.strip()]


def undo_escapes(text: str, currency: str) -> str:
    """Undo the Goldmark escapes of the post, which MathJax on the site needs."""
    text = text.replace("\\\\$", currency)             # currency, written \\$ in the post
    text = re.sub(r"\\\\([,;!{}%])", r"\\\1", text)     # \\, becomes the LaTeX space \,
    text = text.replace("\\\\_", "_").replace("\\_", "_")
    if "\\\\" in text:
        raise SystemExit("index.md contains a Goldmark escape that this script does not handle")
    return text


def apply_wording(text: str, pairs: list[tuple[str, str]], used: dict[str, int]) -> str:
    for old, new in pairs:
        used[old] = used.get(old, 0) + text.count(old)
        text = text.replace(old, new)
    return text


def check_wording(pairs: list[tuple[str, str]], used: dict[str, int]) -> None:
    missing = [old for old, _ in pairs if not used.get(old)]
    if missing:
        raise SystemExit("index.md no longer contains these phrases; update the wording "
                         "lists of regen_companions.py: " + "; ".join(missing))


def common_text(text: str, used: dict[str, int]) -> str:
    text = text.replace("](/post/", f"]({SITE}/post/")
    return apply_wording(text, COMMON_WORDING, used)


def yaml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


