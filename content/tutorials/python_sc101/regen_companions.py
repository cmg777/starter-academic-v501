class Node:
    """One element of the post body: Markdown text, a fence, a card, an image, and so on."""

    def __init__(self, kind: str, **attrs):
        self.kind = kind
        self.children: list[Node] = []
        self.__dict__.update(attrs)


FENCE_OPEN = re.compile(r"^```(\w+)\s*$")
DETAILS_OPEN = re.compile(r'^<details(?: class="([^"]+)")?>$')
SUMMARY = re.compile(r'^<summary>(?:<span class="learn-card-kicker">([^<]+)</span>\s*)?(.+?)</summary>$')
DIV_OPEN = re.compile(r'^<div class="([^"]+)">$')
KICKER = re.compile(r'^<p class="learn-card-kicker">([^<]+)</p>$')
IMAGE = re.compile(r"^!\[([^\]]*)\]\(([\w.-]+\.png)\)$")
CAPTION = re.compile(r"^\*(Figure (\d+)\. .+)\*$")
SHORTCODE = re.compile(r"^\{\{<\s*([\w-]+)\s*>\}\}$")
BADGE = re.compile(r'^<a href="https://colab\.research\.google\.com/[^"]+"[^>]*><img [^>]+></a>$')


def split_front_matter(md: str) -> tuple[str, str, int]:
    """Return the front matter, the body, and the number of lines before the body."""
    if not md.startswith("---\n"):
        raise SystemExit("index.md must start with YAML front matter")
    end = md.index("\n---\n", 4)
    return md[4:end], md[end + 5:], md[:end + 5].count("\n")


def front_scalar(front: str, key: str) -> str:
    m = re.search(rf'^{key}:\s*"?(.*?)"?\s*$', front, re.M)
    if not m:
        raise SystemExit(f"index.md has no {key} in its front matter")
    return m.group(1)


def front_links(front: str) -> list[dict[str, str]]:
    """Parse the links list of the front matter (icon, icon_pack, name, url)."""
    m = re.search(r"(?ms)^links:\n(.*?)(?=^[^\s-]|\Z)", front + "\n")  # items may start at column 0
    items: list[dict[str, str]] = []
    for line in (m.group(1).splitlines() if m else []):
        km = re.match(r"^(-\s+|\s+)(\w+):\s*(.*)$", line)
        if not km:
            continue
        if km.group(1).startswith("-"):
            items.append({})
        if items:
            items[-1][km.group(2)] = km.group(3).strip().strip('"')
    return items


def parse_body(body: str, offset: int) -> Node:
    """Parse the body of the post into a tree of nodes."""
    root = Node("root")
    stack = [root]
    lines = body.split("\n")

    def where(i: int) -> str:
        return f"index.md, line {i + offset + 1}"

    def add(node: Node) -> Node:
        stack[-1].children.append(node)
        return node

    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("```"):
            m = FENCE_OPEN.match(line)
            if not m:
                raise SystemExit(f"{where(i)}: a code fence needs a language: {line!r}")
            end = lines.index("```", i + 1)
            add(Node("fence", lang=m.group(1), code="\n".join(lines[i + 1:end]) + "\n"))
            i = end + 1
            continue
        m = DETAILS_OPEN.match(line)
        if m:
            sm = SUMMARY.match(lines[i + 1])
            if not sm:
                raise SystemExit(f"{where(i + 1)}: a <details> block needs a one-line <summary>")
            node = add(Node("details", cls=m.group(1) or "", kicker=sm.group(1), summary=sm.group(2)))
            stack.append(node)
            i += 2
            continue
        if line == "</details>":
            if stack[-1].kind != "details":
                raise SystemExit(f"{where(i)}: </details> without an open <details>")
            stack.pop()
            i += 1
            continue
        m = DIV_OPEN.match(line)
        if m:
            stack.append(add(Node("div", cls=m.group(1))))
            i += 1
            continue
        if line == "</div>":
            if stack[-1].kind != "div":
                raise SystemExit(f"{where(i)}: </div> without an open <div>")
            stack.pop()
            i += 1
            continue
        m = KICKER.match(line)
        if m:
            add(Node("kicker", text=m.group(1)))
            i += 1
            continue
        m = IMAGE.match(line)
        if m:
            cm = CAPTION.match(lines[i + 1]) if i + 1 < len(lines) else None
            if not cm:
                raise SystemExit(f"{where(i)}: a figure needs an italic caption on the next line")
            add(Node("image", alt=m.group(1), src=m.group(2), caption=cm.group(1)))
            i += 2
            continue
        m = SHORTCODE.match(line)
        if m:
            add(Node("shortcode", name=m.group(1)))
            i += 1
            continue
        if BADGE.match(line):
            add(Node("badge"))
            i += 1
            continue
        if line.startswith("<") and not line.startswith("<http"):
            raise SystemExit(f"{where(i)}: unexpected HTML line: {line[:70]!r}")
        kids = stack[-1].children
        if kids and kids[-1].kind == "md":
            kids[-1].text += "\n" + line
        else:
            add(Node("md", text=line))
        i += 1
    if len(stack) != 1:
        raise SystemExit("index.md has an unclosed <details> or <div> block")
    return root


def walk(node: Node):
    """Yield every descendant of a node in document order."""
    for child in node.children:
        yield child
        yield from walk(child)


def hugo_anchor(heading: str) -> str:
    """Return the anchor that Goldmark (GitHub style) gives a heading on the site."""
    text = re.sub(r"[^\w\- ]", "", heading.strip().lower())
    return text.replace(" ", "-")


STOP_WORDS = {"a", "an", "and", "by", "for", "in", "it", "of", "on", "the", "to", "versus",
              "with"}


def heading_label(heading: str) -> str:
    """Turn a numbered heading into a chunk label, for example s3-1-load-data."""
    m = re.match(r"^(\d+(?:\.\d+)*)\.?\s+(.*)$", heading)
    number, title = (m.group(1), m.group(2)) if m else ("0", heading)
    words = [w for w in re.findall(r"[a-z0-9]+", title.lower()) if w not in STOP_WORDS][:4]
    return "-".join(["s" + number.replace(".", "-"), *words])


def annotate(root: Node) -> dict:
    """Attach headings, figures, exercise numbers, and chunk labels to the nodes."""
    order = list(walk(root))
    heading, exercise = "", None
    fences: list[Node] = []
    stats = {"python": 0, "figures": 0, "cards": {}, "lab_anchor": None}
    for k, node in enumerate(order):
        if node.kind == "md":
            for line in node.text.split("\n"):
                hm = re.match(r"^#{2,6}\s+(.*)$", line)
                if hm:
                    heading = hm.group(1).strip()
                em = re.match(r"^\*\*Exercise (\d+):", line)
                if em:
                    exercise = int(em.group(1))
        elif node.kind == "fence" and node.lang == "python":
            node.heading, node.fig, node.exercise = heading, None, None
            fences.append(node)
        elif node.kind == "image":
            j = k - 1
            while order[j].kind == "md" and not order[j].text.strip():
                j -= 1
            prev = order[j]
            if not (prev.kind == "fence" and prev.lang == "python"):
                raise SystemExit(f"the figure {node.src} does not follow its plotting code")
            prev.fig = node
        elif node.kind == "details":
            node.exercise = exercise
            key = node.cls or "plain"
            stats["cards"][key] = stats["cards"].get(key, 0) + 1
            if node.cls == "learn-card solution-card":
                if exercise is None:
                    raise SystemExit("a solution card precedes every exercise statement")
                for sub in walk(node):
                    if sub.kind == "fence" and sub.lang == "python":
                        sub.solution = exercise
        elif node.kind == "div":
            key = node.cls
            stats["cards"][key] = stats["cards"].get(key, 0) + 1
        elif node.kind == "shortcode":
            if node.name != "sc-lab":
                raise SystemExit(f"no conversion rule for the shortcode {node.name}")
            node.anchor = hugo_anchor(heading)
            stats["lab_anchor"] = node.anchor
    labels = {"setup-packages"}
    counts: dict[str, int] = {}
    for f in fences:
        if f.fig is not None:
            stem = re.sub(r"^sc101_", "", f.fig.src[:-4])
            label = "fig-" + stem.replace("_", "-")
            stats["figures"] += 1
        elif getattr(f, "solution", None):
            label = f"exercise-{f.solution}-solution"
        else:
            base = heading_label(f.heading)
            counts[base] = counts.get(base, 0) + 1
            label = base if counts[base] == 1 else f"{base}-{counts[base]}"
        if label in labels:
            raise SystemExit(f"duplicate chunk label {label}")
        labels.add(label)
        f.label = label
        stats["python"] += 1
    return stats


