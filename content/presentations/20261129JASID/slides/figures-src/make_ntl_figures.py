"""Write the two nighttime-lights figures for the JASID deck as Plotly includes.

    python3 figures-src/make_ntl_figures.py        (run from slides/)

Outputs (spliced into index.html at Quarto render time by `{{< include >}}`):
    figures-src/fig-ntl-scatter.html   slide "Can nighttime lights tell us about poverty?"
    figures-src/fig-ntl-r2.html        slide "R² compares a model with a simple guess"

Data: figures-src/ntl_sdg1_2017.csv, the 339 municipalities decoded from the study's own
interactive scatter (quarcs-lab/project2026e-slides @ bb860234, figures/fig-ntl-sdg1-scatter.html,
written by scripts/fig-ntl-sdg1-scatter.py). x = population-weighted mean VIIRS radiance, 2017
(nW/sr/cm²); y = SDG 1 No Poverty index, 2017 (0-100, higher = less poverty).

These replace two static Matplotlib SVGs (ntl-poverty-scatter.svg, ntl-r2-teaching.svg) whose
embedded glyphs mixed bold and regular weights. Plotly is already loaded for the other four charts,
so the scatter gains hover names at no extra cost. Standard library only; no plotly package needed.
The script asserts the published numbers (mean 37.46, error share 45.6%, R² 0.544) before writing.
"""
import csv
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Deck palette (theme.scss). No new colours.
INK, MUTED, FAINT = "#EEF3F9", "#A9BDD4", "#8199B4"
LIGHTS, EMB, HAIR, SURFACE = "#F5B455", "#8FC0EC", "#2A5183", "#13304F"
FONT = "Inter, 'Helvetica Neue', Arial, sans-serif"
TICK, AXIS = 20, 21

rows = list(csv.DictReader(open(HERE / "ntl_sdg1_2017.csv", encoding="utf-8")))
x = [float(r["ntl_radiance_popweighted_2017"]) for r in rows]
y = [float(r["sdg1_index_2017"]) for r in rows]
names = [[r["municipality"], r["department"]] for r in rows]
n = len(x)
assert n == 339

# OLS of y on ln(x), exactly as the study's scatter.
lx = [math.log(v) for v in x]
mx, my = sum(lx) / n, sum(y) / n
b = sum((a - mx) * (c - my) for a, c in zip(lx, y)) / sum((a - mx) ** 2 for a in lx)
a0 = my - b * mx
fit = [a0 + b * v for v in lx]
sst = sum((c - my) ** 2 for c in y)
sse = sum((c - f) ** 2 for c, f in zip(y, fit))
r2 = 1 - sse / sst
assert round(my, 2) == 37.46 and round(100 * sse / sst, 1) == 45.6 and round(r2, 3) == 0.544, (my, sse / sst, r2)

xmin, xmax = min(x), max(x)
line_x = [xmin * (xmax / xmin) ** (i / 99) for i in range(100)]
line_y = [a0 + b * math.log(v) for v in line_x]


def axis(**kw):
    base = dict(tickfont=dict(size=TICK, color=MUTED), title=dict(font=dict(size=AXIS, color=MUTED)),
                showgrid=True, gridcolor="rgba(42,81,131,0.45)", zeroline=False, showline=True,
                linecolor=HAIR, ticks="outside", tickcolor=HAIR, fixedrange=True)
    base.update(kw)
    return base


def base_layout(width, height, **kw):
    lay = dict(width=width, height=height, autosize=False, paper_bgcolor="rgba(0,0,0,0)",
               plot_bgcolor="rgba(0,0,0,0)", dragmode=False, showlegend=False,
               font=dict(family=FONT, size=TICK, color=INK),
               hoverlabel=dict(font=dict(family=FONT, size=19, color=INK), bgcolor=SURFACE, bordercolor=HAIR))
    lay.update(kw)
    return lay


def write(fig_id, label, data, layout, path):
    spec = dict(data=data, layout=layout,
                config=dict(displayModeBar=False, scrollZoom=False, responsive=False, showTips=False))
    w, h = layout["width"], layout["height"]
    html = (
        f'<div id="{fig_id}" class="plotly-figure" role="img" aria-label="{label}" '
        f'style="width:{w}px;height:{h}px;margin:0 auto;"></div>\n'
        f'<script>(function(){{var s={json.dumps(spec, separators=(",", ":"))};'
        f'Plotly.newPlot("{fig_id}",s.data,s.layout,s.config);}})();</script>\n'
        "<!-- GENERATED by figures-src/make_ntl_figures.py from ntl_sdg1_2017.csv; edit the script, not this file. -->\n"
    )
    path.write_text(html, encoding="utf-8")
    print("wrote", path.name, f"{w}x{h}")


hover = "%{customdata[0]}, %{customdata[1]}<br>Lights %{x:.2f} · Index %{y:.1f}<extra></extra>"
XT = dict(type="log", tickvals=[0.1, 1, 10, 100], ticktext=["0.1", "1", "10", "100"])

# ---- 1. Scatter ---------------------------------------------------------------------------------
scatter = [
    dict(type="scatter", mode="markers", x=x, y=y, customdata=names, hovertemplate=hover,
         marker=dict(size=10, color=LIGHTS, opacity=0.72, line=dict(color="#06101F", width=0.8))),
    dict(type="scatter", mode="lines", x=line_x, y=line_y, hoverinfo="skip",
         line=dict(color=INK, width=3)),
]
lay = base_layout(
    1150, 450, margin=dict(l=96, r=24, t=14, b=78), hovermode="closest",
    xaxis=axis(**XT, range=[math.log10(0.09), math.log10(130)],
               title=dict(text="Brightness of nighttime lights (log scale)", font=dict(size=AXIS, color=MUTED), standoff=10)),
    yaxis=axis(range=[-3, 100], tickvals=[0, 25, 50, 75, 100],
               title=dict(text="No Poverty index", font=dict(size=AXIS, color=MUTED), standoff=8)),
    annotations=[dict(xref="paper", yref="paper", x=0.01, y=0.99, xanchor="left", yanchor="top",
                      showarrow=False, align="left", font=dict(size=20, color=MUTED),
                      text="Higher = less poverty")],
)
write("fig-ntl-scatter",
      "Scatter of 339 Bolivian municipalities in 2017: brightness of nighttime lights on a log scale "
      "against the SDG 1 No Poverty index, with a rising fitted line. Hover a dot for its municipality.",
      scatter, lay, HERE / "fig-ntl-scatter.html")

# ---- 2. R² teaching, two panels -----------------------------------------------------------------
# The same 14 municipalities carry an illustrative error gap in both panels: evenly spaced radiance
# ranks, as in the SVG this replaces. All 339 points enter the statistic.
order = sorted(range(n), key=lambda i: x[i])
pick = [order[round(k * (n - 1) / 13)] for k in range(14)]


def gaps(pred):
    gx, gy = [], []
    for i in pick:
        gx += [x[i], x[i], None]
        gy += [y[i], pred(i), None]
    return gx, gy


g1 = gaps(lambda i: my)
g2 = gaps(lambda i: fit[i])
pts = dict(mode="markers", x=x, y=y, customdata=names, hovertemplate=hover,
           marker=dict(size=8, color=LIGHTS, opacity=0.6, line=dict(width=0)))
r2data = [
    dict(type="scatter", xaxis="x", yaxis="y", **pts),
    dict(type="scatter", mode="lines", x=g1[0], y=g1[1], xaxis="x", yaxis="y", hoverinfo="skip",
         line=dict(color=EMB, width=2.4)),
    dict(type="scatter", mode="lines", x=[xmin * 0.9, xmax * 1.1], y=[my, my], xaxis="x", yaxis="y",
         hoverinfo="skip", line=dict(color=INK, width=3, dash="dash")),
    dict(type="scatter", xaxis="x2", yaxis="y2", **pts),
    dict(type="scatter", mode="lines", x=g2[0], y=g2[1], xaxis="x2", yaxis="y2", hoverinfo="skip",
         line=dict(color=EMB, width=2.4)),
    dict(type="scatter", mode="lines", x=line_x, y=line_y, xaxis="x2", yaxis="y2", hoverinfo="skip",
         line=dict(color=INK, width=3)),
]
xr = [math.log10(0.09), math.log10(130)]
head = dict(xref="paper", yref="paper", y=1.0, yanchor="bottom", showarrow=False, align="left",
            xanchor="left")
lay2 = base_layout(
    1150, 436, margin=dict(l=92, r=20, t=44, b=56), hovermode="closest",
    xaxis=axis(**XT, range=xr, domain=[0, 0.47]),
    yaxis=axis(range=[-3, 100], tickvals=[0, 25, 50, 75, 100],
               title=dict(text="No Poverty index", font=dict(size=AXIS, color=MUTED), standoff=8)),
    xaxis2=axis(**XT, range=xr, domain=[0.53, 1]),
    yaxis2=axis(range=[-3, 100], tickvals=[0, 25, 50, 75, 100], anchor="x2", showticklabels=False),
    annotations=[
        dict(head, x=0, text="<b>1  Guess the average for everyone</b>   (index 37.5)", font=dict(size=21, color=INK)),
        dict(head, x=0.53, text="<b>2  Use the nighttime lights</b>", font=dict(size=21, color=INK)),
        dict(xref="paper", yref="paper", x=0.235, y=-0.14, xanchor="center", yanchor="top", showarrow=False,
             text="Total squared error: <b>100%</b>", font=dict(size=20, color=MUTED)),
        dict(xref="paper", yref="paper", x=0.765, y=-0.14, xanchor="center", yanchor="top", showarrow=False,
             text="Total squared error: <b>45.6%</b> of the guess", font=dict(size=20, color=MUTED)),
    ],
)
lay2["margin"]["b"] = 78
write("fig-ntl-r2",
      "Two panels with the same 339 municipalities. Left: everyone gets the average index, 37.46; blue gaps "
      "show the errors. Right: a fitted line using nighttime lights; total squared error falls to 45.6 percent "
      "of the left panel, so R squared is 0.544.",
      r2data, lay2, HERE / "fig-ntl-r2.html")
print(f"check: mean {my:.4f}  error share {sse / sst:.5f}  R2 {r2:.6f}")
