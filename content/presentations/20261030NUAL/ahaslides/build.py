#!/usr/bin/env python3
"""activities.py + pages.py -> deck.json, deck.md and payload.json.

    python3 build.py

deck.md is the presenter script (every slide in order, with notes).
payload.json groups the create_slides bodies by anchor page; the anchor slide
IDs come from slide_ids.json (page -> slide ID, recorded after the import).
"""
import json
import re
from pathlib import Path

from activities import ACTIVITIES
from pages import LABELS, N_PAGES, VIDEOS, image_pages, youtube_url

HERE = Path(__file__).parent
BANNED = [(r"—", "em dash"), (r"\b\w+'(t|s|re|ll|ve|d)\b", "contraction or possessive")]


def texts(slide):
    yield slide.get("heading", "")
    for o in slide.get("options", []):
        yield o["text"] if isinstance(o, dict) else o


ids = [a["id"] for a in ACTIVITIES]
assert len(ids) == len(set(ids)), "duplicate activity id"
for a in ACTIVITIES:
    assert 1 <= a["after"] <= N_PAGES and a["after"] not in VIDEOS, a["id"]
    for t in texts(a["slide"]):
        for pat, what in BANNED:
            assert not re.search(pat, t), f"{a['id']}: {what} in {t!r}"
    if a["slide"]["slide_type"] == "poll":
        assert "correct" not in a["slide"], f"{a['id']}: a poll has no correct option"

deck = []
for p in range(1, N_PAGES + 1):
    if p in VIDEOS:
        deck.append({"kind": "youtube", "page": p, "label": LABELS[p],
                     "url": youtube_url(p), "title": VIDEOS[p][1]})
    else:
        deck.append({"kind": "image", "page": p, "label": LABELS[p]})
    for a in ACTIVITIES:
        if a["after"] == p:
            deck.append({"kind": a["slide"]["slide_type"], "id": a["id"],
                         "label": a["slide"].get("heading", "Join code"),
                         "notes": a["notes"]})
for i, s in enumerate(deck, 1):
    s["position"] = i
(HERE / "deck.json").write_text(json.dumps(deck, indent=2, ensure_ascii=False) + "\n")

n_img, n_vid = len(image_pages()), len(VIDEOS)
lines = ["# NUAL keynote: AhaSlides deck order", "",
         f"{len(deck)} slides = {n_img} images + {n_vid} YouTube + "
         f"{len(ACTIVITIES)} interactive. Generated by build.py; do not edit.", "",
         "| # | Page | Slide |", "|---|---|---|"]
for s in deck:
    if s["kind"] == "image":
        lines.append(f"| {s['position']} | {s['page']} | {s['label']} |")
    elif s["kind"] == "youtube":
        lines.append(f"| {s['position']} | {s['page']} | YouTube: {s['title']} ({s['url']}) |")
    else:
        lines.append(f"| {s['position']} | | **{s['id']} {s['kind']}**: {s['label']} |")
lines += ["", "## Presenter notes", ""]
for s in deck:
    if "notes" in s:
        lines += [f"**{s['id']}** ({s['kind']}, slide {s['position']}): {s['notes']}", ""]
(HERE / "deck.md").write_text("\n".join(lines))

slide_ids = {}
if (HERE / "slide_ids.json").exists():
    slide_ids = json.loads((HERE / "slide_ids.json").read_text()).get("pages", {})
def body(a):
    """The create_slides body. Options are sent as written: on 2026-10-25 the
    editor displayed {"text": ...} poll options in payload order, NOT reversed
    as .claude/docs/ahaslides.md records for the older string options."""
    return dict(a["slide"], notes=a["notes"])


calls = []
for page in sorted({a["after"] for a in ACTIVITIES}):
    group = [a for a in ACTIVITIES if a["after"] == page]
    calls.append({"after_page": page,
                  "insert_after_slide_id": slide_ids.get(str(page)),
                  "ids": [a["id"] for a in group],
                  "slides": [body(a) for a in group],
                  "props": {a["id"]: a["props"] for a in group}})
(HERE / "payload.json").write_text(json.dumps(calls, indent=2, ensure_ascii=False) + "\n")
print(f"deck: {len(deck)} slides ({n_img} images, {n_vid} videos, {len(ACTIVITIES)} interactive); "
      f"payload: {len(calls)} create_slides calls; anchors known: "
      f"{sum(c['insert_after_slide_id'] is not None for c in calls)}/{len(calls)}")
